export function getCatalogItemBySlug(slug: string): CatalogPageItem | undefined {
  // Normalize slug: remove leading/trailing slashes and .html extension
  const clean = slug.replace(/^\/+|\/+$/g, "").replace(/\.html$/, "");
  return CATALOG_PAGES.find((item) => {
    const itemClean = item.slug.replace(/^\/+|\/+$/g, "");
    if (itemClean === clean) return true;
    if (item.aliases && item.aliases.some((a) => a.replace(/^\/+|\/+$/g, "").replace(/\.html$/, "") === clean)) {
      return true;
    }
    return false;
  });
}
